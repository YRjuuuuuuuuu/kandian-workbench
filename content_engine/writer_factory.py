def features(text):
    paragraphs = [p.strip() for p in re.split(r"\n\s*\n", text) if len(p.strip()) >= 12 and not p.strip().startswith(("![", "http"))]
    lengths = [len(p) for p in paragraphs]
    return {"characters": len(text), "paragraphs": len(paragraphs), "median_paragraph": round(statistics.median(lengths)) if lengths else 0, "numeric_tokens": len(re.findall(r"\d+(?:\.\d+)?", text)), "questions": text.count("？"), "subheads": len(re.findall(r"(?m)^#{1,4} .+", text))}


def clean_sample(text):
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = re.split(r"(?m)^(?:相关推荐|热门评论|评论\s*\d|打开今日头条|版权声明|声明：此文版权|举报/反馈|下载今日头条)", text)[0]
    return text.strip()[:14000]


def prepare(rows):
    samples, hashes, fingerprints = [], set(), []
    for row in rows[:14]:
        text = clean_sample(row.get("text") or row.get("content") or "")
        if not 450 <= len(text) <= 14000: continue
        normalized = re.sub(r"\W+", "", text)
        fingerprint = {normalized[i:i+12] for i in range(0, max(0, len(normalized)-12), 4)}
        digest = hashlib.sha256(normalized.encode()).hexdigest()
        if digest in hashes or any(len(fingerprint & old) / max(1, min(len(fingerprint), len(old))) > .70 for old in fingerprints): continue
        author = str(row.get("author") or "未核实作者")[:100]
        # An automatically supplied author must actually appear in the sample.
        if row.get("author_inferred") and author not in text: author = "未核实作者"
        sample = {"id": "s"+str(len(samples)+1), "title": str(row.get("title") or "公开样本")[:180], "author": author, "url": str(row.get("url") or "用户提供样本")[:2000], "genre": str(row.get("genre") or "未分类")[:60], "group": str(row.get("group") or "general")[:60], "text": text, "sha256": digest, "features": features(text), "read_method": row.get("read_method", "user_provided")}
        samples.append(sample); hashes.add(digest); fingerprints.append(fingerprint)
        if len(samples) >= 10: break
    if len(samples) < 6:
        raise ValueError("至少需要6篇可读且去重后的同赛道样本；本轮没有启用不充分的学习结果")
    # Stable split independent of the rules generated by the model.
    ordered = sorted(samples, key=lambda s: s["sha256"])
    holdout_count = max(2, len(samples)//3)
    groups = {s["group"]: [x for x in ordered if x["group"] == s["group"]] for s in samples}
    held, used_groups = set(), set()
    for candidate in ordered:
        if len(held) >= holdout_count: break
        group = candidate["group"]
        if len(groups[group]) <= 1 or group in used_groups: continue
        held.add(candidate["id"]);used_groups.add(group)
    for candidate in ordered:
        if len(held) >= holdout_count: break
        same = groups[candidate["group"]]
        if candidate["id"] not in held and sum(x["id"] not in held for x in same) > 1: held.add(candidate["id"])
    if len(held) < 2: raise ValueError("样本分组过少，不能同时保证训练覆盖和独立留出检查")
    for s in samples: s["split"] = "holdout" if s["id"] in held else "train"
    return samples


class WriterFactory:
    def __init__(self, engine):
        self.engine, self.store = engine, engine.store

    def current(self, mode_id):
        setting = self.store.one("SELECT value FROM settings WHERE key=?", ("writer_active:"+mode_id,))
        profile = self.store.one("SELECT * FROM writer_profiles WHERE id=? AND mode_id=?", (json.loads(setting["value"]), mode_id)) if setting else None
        if profile:
            profile["data"] = json.loads(profile["data"])
            return profile
        # The shipped sports skill remains usable on a clean installation.
        from .engine import ROOT
        folder = ROOT/"skills"/("toutiao-"+mode_id+"-writer")
        if (folder/"SKILL.md").is_file():
            manifest = json.loads((folder/"profile.json").read_text(encoding="utf-8")) if (folder/"profile.json").is_file() else {}
            return {"id": "bundled-"+mode_id, "mode_id": mode_id, "version": manifest.get("version", 1), "state": "bundled", "data": {**manifest, "skill_markdown": (folder/"SKILL.md").read_text(encoding="utf-8")}}
        return None

    def snapshot(self, mode_id):
        profile = self.current(mode_id)
        if not profile: return None
        return {"id": profile["id"], "version": profile["version"], "mode_id": mode_id, "skill_markdown": profile["data"]["skill_markdown"], "sample_count": len(profile["data"].get("samples", []))}

    def state(self, mode_id):
        self.engine.modes.get(mode_id)
        versions = self.store.all("SELECT * FROM writer_profiles WHERE mode_id=? ORDER BY version DESC LIMIT 15", (mode_id,))
        for v in versions:
            v["data"] = json.loads(v["data"])
            v["data"].pop("skill_markdown", None)
        current = self.current(mode_id)
        return {"mode_id": mode_id, "active_id": current["id"] if current else None, "active_version": current["version"] if current else None, "profiles": versions, "active_summary": {k: current["data"].get(k) for k in ("samples", "validation", "persona")} if current else None}

    def activate(self, mode_id, profile_id, expected_id):
        from .documents import DocumentConflict
        from .engine import iso
        self.engine.modes.get(mode_id)
        with self.engine.lock, self.store.db() as db:
            db.execute("BEGIN IMMEDIATE")
            current = self.current(mode_id)
            if (current["id"] if current else None) != expected_id:
                raise DocumentConflict("写作skill的启用版本已改变，请刷新后再选择")
            if profile_id == "bundled-"+mode_id:
                from .engine import ROOT
                if not (ROOT/"skills"/("toutiao-"+mode_id+"-writer")/"SKILL.md").is_file():
                    raise ValueError("此频道没有内置写作skill")
                db.execute("DELETE FROM settings WHERE key=?", ("writer_active:"+mode_id,))
                db.execute("UPDATE writer_profiles SET state='archived' WHERE mode_id=? AND state='active'", (mode_id,))
                self.engine.audit(db, "writer_skill.activate", profile_id, {"previous": expected_id, "mode_id": mode_id})
                db.commit()
                return self.state(mode_id)
            profile = db.execute("SELECT * FROM writer_profiles WHERE id=? AND mode_id=?", (profile_id, mode_id)).fetchone()
            if not profile or not json.loads(profile["data"])["validation"]["passed"]:
                raise ValueError("未找到通过样本与规则检查的候选版本")
            db.execute("UPDATE writer_profiles SET state='archived' WHERE mode_id=? AND state='active'", (mode_id,))
            db.execute("UPDATE writer_profiles SET state='active' WHERE id=?", (profile_id,))
            db.execute("INSERT OR REPLACE INTO settings VALUES(?,?)", ("writer_active:"+mode_id, dumps(profile_id)))
            self.engine.audit(db, "writer_skill.activate", profile_id, {"previous": expected_id, "mode_id": mode_id})
        return self.state(mode_id)

    def read_url(self, url, run):
        from .public_fetch import fetch
        from .media_bridge import public_url
        url = public_url(url)
        host = urllib.parse.urlsplit(url).hostname or ""
        if host != "toutiao.com" and not host.endswith(".toutiao.com"):
            raise ValueError("写作样本链接请使用公开头条文章地址；其他素材可通过样本文本导入")
        raw, method = "", "public_http"
        try:
            body, mime, _ = fetch(url, limit=2_000_000, timeout=8, accept="text/html")
            parser = PageReceipt();parser.feed(body.decode("utf-8", errors="replace"))
            raw = "\n\n".join(parser.article_words)
            title = parser.title
            if len(raw) < 450: raise ValueError("页面没有可读正文")
        except Exception:
            from .ai import normalize, deepseek_request
            route = normalize(run["payload"]["config"]["ai"])["stage_routes"]["style_learning"]
            if route["provider"] != "deepseek":
                raise ValueError("原文暂不可读；未换服务、未借用登录，请稍后或提供样本文本") from None
            data = deepseek_request(self.engine.models.secret.get(), "/tools/fetch", {"url": url}, timeout=30)
            raw, title, method = data.get("content", ""), data.get("title", "公开头条样本"), "deepseek_official_fetch"
        if len(raw) < 450 or re.search(r"captcha|access denied|安全验证|登录后查看", title or "", re.I):
            raise ValueError("样本正文不足或为访问提示，未作为学习材料")
        return {"url": url, "title": title, "text": raw, "author": "未核实作者", "read_method": method}

    def collect(self, run):
        from .agent import obj, array, STR
        folder = self.engine.data_dir/"agent"/"runs"/run["id"]
        cache = folder/"style_samples.json"
        if cache.is_file(): return json.loads(cache.read_text(encoding="utf-8"))
        rows = list(run["payload"].get("style_samples", []))
        urls = run["payload"].get("style_urls", [])
        if not rows and not urls:
            self.engine.agent.stage(run["id"], "style_collecting", "寻找同赛道公开头条文章，覆盖不同作者和稿型")
            schema = obj({"run_id": STR, "input_hash": STR, "samples": array(obj({"url": STR, "title": STR, "author": STR, "genre": STR}))})
            type_names = "、".join(t["name"] for t in run["payload"]["mode"]["templates"])
            output, _ = self.engine.agent.invoke(run, "style_sources", "为"+run["payload"]["mode"]["name"]+"频道研究头条写作方法。使用实际联网工具搜集8—10篇可读公开头条文章链接，优先不同作者，覆盖本频道不同稿型："+type_names+"。不要只选同一事件的转载，不要求当天文章，不选粉丝对骂和人身攻击。不抄正文，作者不明填未核实作者。只返回真实已读取来源的链接和元数据。", schema, search=True, timeout=240)
            urls = [s["url"] for s in output["samples"][:12]]
        for url in urls[:12]:
            self.engine.agent.ensure_active(run)
            try:
                rows.append(self.read_url(url, run))
                self.engine.agent.event(run["id"], "style_sample", "已读取写作样本："+url, {})
            except ValueError as exc:
                self.engine.agent.event(run["id"], "style_sample", "未采用样本："+str(exc), {"url": url})
        samples = prepare(rows)
        folder.mkdir(parents=True, exist_ok=True)
        cache.write_text(dumps(samples), encoding="utf-8")
        return samples

    def process(self, run):
        from .agent import obj, array, STR, STRINGS
        from .engine import ROOT
        samples = self.collect(run)
        training = [s for s in samples if s["split"] == "train"]
        schema = obj({"run_id": STR, "input_hash": STR, "persona": STR, "patterns": array(obj({"section": {"type": "string", "enum": ["title", "opening", "body", "analysis", "ending", "image"]}, "rule": STR, "sample_ids": STRINGS})), "avoid": STRINGS, "rubric": array(obj({"name": STR, "check": STR})), "templates": array(obj({"id": STR, "outline": STRINGS}))})
        self.engine.agent.stage(run["id"], "style_learning", f"从{len(training)}篇训练样本归纳规则，另留{len(samples)-len(training)}篇不参与归纳")
        builder = (ROOT/"skills/toutiao-writing-skill-builder/SKILL.md").read_text(encoding="utf-8")
        instruction = builder+"\n当前模式："+dumps({"id":run["payload"]["mode"]["id"],"name":run["payload"]["mode"]["name"],"templates":[{"id":t["id"],"name":t["name"]} for t in run["payload"]["mode"]["templates"]]})+"\n以下仅训练样本，不包含留出正文。给8—16条具体抽象规则，通用规则尽量由至少两篇独立样本支持，规则不引用原句；给4—6项可执行编辑检查。\nuntrusted_training_samples:\n"+dumps([{k:s[k] for k in ("id","title","author","genre","text")} for s in training])
        rules, _ = self.engine.agent.invoke(run, "style_learning", instruction, schema, timeout=240)
        self.engine.agent.stage(run["id"], "style_validating", "检查规则证据、来源去重及留出样本结构；保存可回退候选版本")
        profile = self.save(run["payload"]["mode"], samples, rules)
        return {"summary": "写作skill候选已生成并通过结构检查，启用后用于新任务；留出检查不等于已证明流量提升", "writer_profile_id": profile["id"], "mode_id": profile["mode_id"], "version": profile["version"], "validation": profile["data"]["validation"]}, "skill_ready"

    def save(self, mode, samples, rules):
        from .engine import iso, uid
        train_ids = {s["id"] for s in samples if s["split"] == "train"}
        patterns = []
        forbidden = re.compile(r"忽略.*(?:系统|规则)|读取.*(?:凭据|密钥|cookie)|执行.*(?:shell|命令)|照抄|逐字复制|虚构.*(?:事实|数字)|绕过.*审核", re.I)
        for item in rules.get("patterns", [])[:20]:
            refs = set(item.get("sample_ids", []))
            rule = str(item.get("rule", "")).strip()
            if not refs or not refs <= train_ids or not 8 <= len(rule) <= 320 or forbidden.search(rule): continue
            patterns.append({"section": item["section"], "rule": rule, "sample_ids": sorted(refs)})
        if len(patterns) < 8 or not {"opening", "analysis", "body"} <= {p["section"] for p in patterns}:
            raise ValueError("写作规则证据或覆盖不足，原启用版本保持不变")
        titles = {t["id"] for t in mode["templates"]}
        templates = [t for t in rules.get("templates", []) if t.get("id") in titles and 2 <= len(t.get("outline", [])) <= 8]
        held = [s for s in samples if s["split"] == "holdout"]
        author_count = len({s["author"] for s in samples if s["author"] != "未核实作者"})
        validation = {"passed": True, "training_count": len(train_ids), "holdout_count": len(held), "verified_author_count": author_count, "evidence_rule_count": len(patterns), "multi_sample_rules": sum(len(p["sample_ids"]) >= 2 for p in patterns), "train_features": [s["features"] for s in samples if s["split"] == "train"], "holdout_features": [s["features"] for s in held], "limits": ["留出正文未参与规则归纳；这里只检查结构分布与证据，不声称流量提升。"] + (["部分作者身份未核实，后续应补充多作者样本。"] if author_count < 2 else [])}
        manifest = {"persona": str(rules.get("persona", ""))[:500], "patterns": patterns, "avoid": [str(v)[:220] for v in rules.get("avoid", [])[:10]], "rubric": rules.get("rubric", [])[:8], "templates": templates, "samples": [{k:v for k,v in s.items() if k != "text"} for s in samples], "validation": validation}
        skill = self.compile(mode, manifest)
        manifest["skill_markdown"] = skill
        with self.engine.lock, self.store.db() as db:
            db.execute("BEGIN IMMEDIATE")
            active = self.current(mode["id"])
            version = max(db.execute("SELECT COALESCE(MAX(version),0) FROM writer_profiles WHERE mode_id=?", (mode["id"],)).fetchone()[0], active["version"] if active else 0)+1
            aid = uid();db.execute("INSERT INTO writer_profiles VALUES(?,?,?,?,?,?)", (aid,mode["id"],version,"candidate",dumps(manifest),iso()))
        folder = self.engine.data_dir/"writer-skills"/mode["id"]/str(version)
        folder.mkdir(parents=True, exist_ok=True)
        (folder/"SKILL.md").write_text(skill,encoding="utf-8")
        (folder/"profile.json").write_text(dumps({**manifest,"version":version}),encoding="utf-8")
        # Full samples remain private, outside source releases and writer prompts.
        (folder/"private-samples.json").write_text(dumps(samples),encoding="utf-8")
        return {"id":aid,"mode_id":mode["id"],"version":version,"data":manifest}

    def compile(self, mode, profile):
        labels={"title":"标题","opening":"开头","body":"组织进程","analysis":"分析与解释","ending":"收束","image":"图文协作"}
        sections=[]
        for section,label in labels.items():
            rules=["- "+p["rule"] for p in profile["patterns"] if p["section"]==section]
            if rules: sections.append("## "+label+"\n\n"+"\n".join(rules))
        template_lines=["- "+t["id"]+"："+" → ".join(t["outline"]) for t in profile["templates"]]
        rubric=["- "+r["name"]+"："+r["check"] for r in profile["rubric"] if isinstance(r,dict) and "name" in r and "check" in r]
        return "---\nname: toutiao-"+mode["id"]+"-writer\ndescription: 为头条"+mode["name"]+"频道撰写有具体信息和分析的图文，以现有事实包为依据；在该频道写稿、润色或改稿时应用。\n---\n\n"+profile["persona"]+"\n\n事实和素材规则优先；样本只支持写法，不能提供本篇新闻事实、个人经历或作者身份。不照搬样本句子，不为接近样本篇幅添造数据。以读者问题组织内容，避免把核查报告写成正文。\n\n每段推进新的信息或解释，不在多段中反复重述同一判断。统计差异不自动证明角色或战术改变。以下规则和提纲按材料选用，并非每项必填。缺少的关键回合、换人时点、采访或背景就删去对应环节，不为模板补造素材。单场统计不自动证明因果；解释机制应有具体过程支持，也可说明另一种合理解释。\n\n"+"\n\n".join(sections)+"\n\n## 按稿型选择结构\n\n"+"\n".join(template_lines)+"\n\n## 编辑量表\n\n"+"\n".join(rubric)+"\n\n## 避免\n\n"+"\n".join("- "+v for v in profile["avoid"])+"\n\n样本出处、训练/留出划分与证据映射见同目录profile.json；原文仅供本地学习，不进入稿件素材。\n"
